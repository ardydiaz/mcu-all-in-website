import { Router } from "express";
import { AnnouncementController } from "../controllers/AnnouncementController.js";
import { authMiddleware } from "../middleware/authMiddleware.js";
import { adminOnly } from "../middleware/roleMiddleware.js";
import { validate } from "../middleware/validationMiddleware.js";
import { announcementValidation } from "../validations/announcement.validation.js";
const router = Router();
router.use(authMiddleware, adminOnly);
router.get("/", AnnouncementController.index);
router.post("/", validate(announcementValidation), AnnouncementController.store);
router.get("/:id", AnnouncementController.show);
router.put("/:id", validate(announcementValidation), AnnouncementController.update);
router.delete("/:id", AnnouncementController.destroy);
router.patch("/:id/restore", AnnouncementController.restore);
export default router;
